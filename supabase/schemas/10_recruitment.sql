-- One qualification record per company; jobs are supporting evidence, not customers.
create table public.recruitment (
  id bigint generated by default as identity primary key,
  company_id bigint not null unique references public.companies(id) on delete cascade,
  jobs jsonb not null default '[]'::jsonb check (jsonb_typeof(jobs) = 'array'),
  pain_points text,
  matched_features text,
  score smallint check (score between 1 and 5),
  business_email text,
  email_source text,
  email_verified boolean not null default false,
  status text not null default 'research' check (status in ('research', 'confirmed', 'contacted', 'replied')),
  created_at timestamptz not null default now(),
  constraint verified_email_has_source check (not email_verified or (nullif(trim(business_email), '') is not null and nullif(trim(email_source), '') is not null))
);
alter table public.recruitment enable row level security;
revoke all on public.recruitment from anon, authenticated;
grant select, insert, update, delete on public.recruitment to authenticated;
grant usage, select on sequence public.recruitment_id_seq to authenticated;
create policy "Active members manage recruitment" on public.recruitment
  for all to authenticated
  using ((select crm_private.is_active_member()))
  with check ((select crm_private.is_active_member()));

-- Keep historical tasks when a recruitment record is removed.
alter table public.tasks add column recruitment_id bigint references public.recruitment(id) on delete set null;
create index tasks_recruitment_id_idx on public.tasks(recruitment_id);
-- A next follow-up is created only after the current one is completed.
create unique index tasks_one_open_recruitment on public.tasks(recruitment_id)
where recruitment_id is not null and done_date is null;
